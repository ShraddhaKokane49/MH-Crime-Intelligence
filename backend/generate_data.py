    print(f"Stations: {sum(len(v) for v in DISTRICTS.values())} across {len(DISTRICTS)} Maharashtra districts")
    print(f"Suspects: {N_SUSPECTS} | Victims: {N_VICTIMS}")
    print("\nInjected ground-truth patterns:")
    print(f"1. Base rates: {BASE_RATE}")
    print(f"2. Weekend multipliers: {WEEKEND_MULTIPLIER}")
    print(f"3. Night-hour multipliers (22:00-04:00): {NIGHT_MULTIPLIER}")
    print(f"4. Seasonal spike (Oct-Nov): {SEASONAL_MULTIPLIER}")
    print(f"5. Hotspot station: '{HOTSPOT_STATION}' ({HOTSPOT_CRIME} x{HOTSPOT_MULTIPLIER})")
    print(f"6. Recent spike: '{RECENT_SPIKE_STATION}' ({RECENT_SPIKE_CRIME} x{RECENT_SPIKE_MULTIPLIER}, last {RECENT_SPIKE_WEEKS} wks)")
    print(f"7. MO ring: 5 suspects (ids {ring_suspects}) across {ring_incident_count} incidents")
